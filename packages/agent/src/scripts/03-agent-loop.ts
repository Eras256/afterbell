/**
 * Afterbell agent loop: after-hours gate -> portfolio snapshot -> rebalance
 * plan -> dashboard state file. Read-only against the chain and NEVER signs
 * or sends anything -- trade execution (Jupiter swaps) is out of scope for
 * this pass; the plan is logged/printed for a human to act on.
 *
 * Point it at Surfpool for local testing:
 *   SOLANA_RPC_URL=http://127.0.0.1:8899 npx tsx src/scripts/03-agent-loop.ts
 *
 * Usage:
 *   npx tsx src/scripts/03-agent-loop.ts             # single pass
 *   npx tsx src/scripts/03-agent-loop.ts --loop 60    # poll every 60s
 *   npx tsx src/scripts/03-agent-loop.ts --force      # ignore market-session gate
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getConnection, loadTeamWallet } from '../lib/env.js';
import { getMarketSession, isAfterHours } from '../lib/market-hours.js';
import { getPortfolioSnapshot } from '../lib/monitor.js';
import { computeRebalancePlan } from '../lib/rebalance.js';
import { BASKET_TARGET_WEIGHTS } from '../lib/basket.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DASHBOARD_STATE_PATH = resolve(__dirname, '../../dashboard/state.js');

async function runOnce(force: boolean) {
  const connection = getConnection();
  const wallet = loadTeamWallet();
  const session = getMarketSession();
  const gateOpen = force || isAfterHours();

  console.log(`[${new Date().toISOString()}] Market session: ${session}${force ? ' (--force, gate ignored)' : ''}`);

  if (!gateOpen) {
    console.log('Outside after-hours window -- agent stays idle. Pass --force to run anyway (testing only).');
    await writeState({ session, gateOpen: false, snapshot: null, plan: null });
    return;
  }

  console.log(`Wallet: ${wallet.publicKey.toBase58()}`);
  const snapshot = await getPortfolioSnapshot(connection, wallet.publicKey);
  console.log('Portfolio snapshot:', JSON.stringify(snapshot, null, 2));

  const plan = computeRebalancePlan(snapshot, BASKET_TARGET_WEIGHTS);
  console.log('Rebalance plan (not executed):', JSON.stringify(plan, null, 2));

  await writeState({ session, gateOpen: true, snapshot, plan });
}

async function writeState(state: unknown) {
  await mkdir(dirname(DASHBOARD_STATE_PATH), { recursive: true });
  const js = `// Generated by 03-agent-loop.ts -- do not edit by hand.\nwindow.AFTERBELL_STATE = ${JSON.stringify(state, null, 2)};\n`;
  await writeFile(DASHBOARD_STATE_PATH, js, 'utf-8');
  console.log(`Dashboard state written to ${DASHBOARD_STATE_PATH}`);
}

async function main() {
  const args = process.argv.slice(2);
  const force = args.includes('--force');
  const loopIdx = args.indexOf('--loop');
  const loopSeconds = loopIdx !== -1 ? Number(args[loopIdx + 1]) : null;

  await runOnce(force);

  if (loopSeconds && loopSeconds > 0) {
    console.log(`Looping every ${loopSeconds}s. Ctrl+C to stop.`);
    setInterval(() => {
      runOnce(force).catch((err) => console.error('Agent loop iteration failed:', err));
    }, loopSeconds * 1000);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
